"""python -m audit <command>

  data         generate the synthetic quarter (seeded) and the hidden answer key
  up / down    build images and start/stop the services (docker compose)
  run          run one engagement (live agents or a scripted agent) through sandbox + gate
  relay        publish approved actions from the transactional outbox to the executor queue
  execute      run the executor (use --redeliver to simulate duplicate delivery)
  review       human review queue: list | show ID | approve ID | reject ID
  verify-log   verify the audit log hash chain
  eval         run N live engagements and report recall/precision/pass^k/cost/turns
  demo         the end-to-end demo (add --offline to skip the live agent run)
"""

# How this file fits in
# ---------------------
# Used by:  audit/__main__.py (`python -m audit <cmd>`), the Makefile, and audit/demo.py (which calls cmd_* directly).
# Calls:    data.generate + executor.handlers.provision_credentials (data)
#           docker build / docker compose (up, down) to start auditlog, erp, broker, policy, egress
#           orchestrator.engagement.run_engagement (run) -> sandbox container -> gate
#           outbox.relay.publish (relay), executor.worker.Executor (execute), review.cli (review)
#           auditlog.chain.verify (verify-log), evals.run.run_evals (eval), demo.run_demo (demo)
# Data:     reads .env (ERP_API_KEY, CASE_TOKEN_SECRET) into os.environ so the orchestrator can mint
#           case tokens; points the audit-log client at the auditlog service (127.0.0.1:8200) when it is up.
from __future__ import annotations

import argparse
import json
import os
import secrets
import subprocess
import sys
import time

from audit.common import config

ENV_FILE = config.ROOT / ".env"


# ---------------------------------------------------------------------------
# environment
# ---------------------------------------------------------------------------

def load_env() -> None:
    if ENV_FILE.exists():
        for line in ENV_FILE.read_text(encoding="utf-8").splitlines():
            if "=" in line and not line.lstrip().startswith("#"):
                k, v = line.split("=", 1)
                os.environ.setdefault(k.strip(), v.strip())


def ensure_env_file() -> None:
    """Create .env with random service secrets (never the Anthropic key)."""
    if not ENV_FILE.exists():
        ENV_FILE.write_text(
            "# Generated by `python -m audit up`. Service secrets for the prototype.\n"
            "# ANTHROPIC_API_KEY is deliberately NOT stored here: export it in your shell.\n"
            f"ERP_API_KEY=erp-{secrets.token_hex(16)}\n"
            f"CASE_TOKEN_SECRET={secrets.token_hex(32)}\n", encoding="utf-8")
    load_env()


def use_auditlog_service_if_up() -> bool:
    import httpx

    try:
        httpx.get("http://127.0.0.1:8200/health", timeout=2).raise_for_status()
    except Exception:
        return False
    os.environ["AUDITLOG_URL"] = "http://127.0.0.1:8200"
    from audit.common.auditlog_client import get_audit_log
    get_audit_log.cache_clear()
    return True


def sh(cmd: list[str], check: bool = True) -> int:
    print("$", " ".join(cmd), flush=True)
    return subprocess.run(cmd, cwd=config.ROOT, check=check).returncode


def wait_healthy(timeout: float = 90) -> None:
    import httpx

    deadline = time.time() + timeout
    print(f"Waiting for services to become healthy (up to {int(timeout)}s)...", flush=True)
    for url in ("http://127.0.0.1:8200/health", "http://127.0.0.1:8100/health"):
        while True:
            try:
                httpx.get(url, timeout=2).raise_for_status()
                break
            except Exception:
                if time.time() > deadline:
                    raise SystemExit(f"service not healthy: {url}")
                time.sleep(1)


# ---------------------------------------------------------------------------
# commands
# ---------------------------------------------------------------------------

def cmd_data(args) -> None:
    from audit.data.generate import generate
    from audit.executor.handlers import provision_credentials

    config.ensure_dirs()
    key = generate(seed=args.seed)
    provision_credentials()
    print(f"Wrote {config.SOURCE_DIR} and the hidden answer key ({len(key['expected_findings'])} planted exceptions).")


def cmd_up(args) -> None:
    config.ensure_dirs()
    ensure_env_file()
    if not (config.SOURCE_DIR / "payments.csv").exists():
        cmd_data(argparse.Namespace(seed=42))
    if not os.environ.get("ANTHROPIC_API_KEY"):
        print("note: ANTHROPIC_API_KEY is not set; scripted runs work, live agent runs will fail at the egress proxy.")
    sh(["docker", "build", "-q", "-t", "audit-sandbox:latest", "-f", "sandbox/Dockerfile", "."])
    sh(["docker", "build", "-q", "-t", "audit-services:latest", "-f", "services.Dockerfile", "."])
    sh(["docker", "compose", "up", "-d", "--force-recreate"])
    wait_healthy()
    use_auditlog_service_if_up()
    print("Services are up.")


def cmd_down(args) -> None:
    sh(["docker", "compose", "down"])


def print_gate(result) -> None:
    for g in result.gate_results:
        print(f"  attempt {g.attempt}: gate outcome = {g.outcome.upper()}"
              + (f" ({g.escalation_reason})" if g.escalation_reason else ""))
        for c in g.checks:
            mark = "ok  " if c.ok else "FAIL"
            print(f"    [{mark}] {c.name}" + ("" if c.ok else ""))
            for d in c.details[:6]:
                print(f"           - {d}")


def cmd_run(args):
    from audit.orchestrator.engagement import run_engagement

    use_auditlog_service_if_up()
    result = run_engagement(mode=args.mode, script=args.script, timeout_s=args.timeout,
                            max_budget_usd=args.budget, max_turns=args.max_turns)
    print(f"Engagement {result.engagement_id} ({args.mode}{'' if args.mode == 'live' else ':' + args.script})")
    for a in result.attempts:
        s = a.summary
        print(f"  attempt {a.attempt}: run {s.get('subtype')}, turns={s.get('num_turns')}, "
              f"cost=${s.get('total_cost_usd')}, wall={s.get('wall_seconds')}s")
    print_gate(result)
    print(f"  actions enqueued: {len(result.action_ids)}")
    return result


def cmd_relay(args) -> int:
    from audit.outbox import db
    from audit.outbox.relay import connect_queue, publish

    use_auditlog_service_if_up()
    n = publish(db.connect(), connect_queue())
    print(f"relay: published {n} new action(s) to the executor queue")
    return n


def cmd_execute(args) -> dict:
    from audit.executor.worker import Executor, connect_ledger
    from audit.outbox import db
    from audit.outbox.relay import connect_queue

    use_auditlog_service_if_up()
    queue = connect_queue()
    if args.redeliver:
        n = queue.execute("UPDATE queue SET status = 'pending' WHERE status = 'done'").rowcount
        print(f"redeliver: put {n} already-executed action(s) back on the queue (simulated duplicate delivery)")
    stats = Executor(db.connect(), queue, connect_ledger()).run()
    print(f"executor: {stats}")
    return stats


def cmd_review(args) -> None:
    from audit.outbox import db
    from audit.review import cli as review

    use_auditlog_service_if_up()
    conn = db.connect()
    if args.action == "list":
        items = review.list_items(conn)
        if not items:
            print("review queue is empty")
        for it in items:
            print(f"#{it['id']:<4} {it['engagement_id']}  {it['source']:<8} {it['action']}")
            for r in it["reasons"][:3]:
                print(f"        - {r}")
    elif args.action == "show":
        print(review.show(conn, args.id))
    else:
        print(review.decide(conn, args.id, approve=args.action == "approve", by=args.by, note=args.note or ""))


def cmd_verify_log(args) -> bool:
    from audit.auditlog.chain import verify

    ok, n, msg = verify(config.AUDIT_LOG)
    print(f"audit log {config.AUDIT_LOG}: {msg}")
    return ok


def cmd_eval(args) -> None:
    from audit.evals.run import run_evals

    use_auditlog_service_if_up()
    run_evals(n=args.n, k=args.k, mode=args.mode, budget=args.budget, timeout=args.timeout)


def cmd_demo(args) -> None:
    from audit.demo import run_demo

    run_demo(offline=args.offline, skip_up=args.skip_up)


def main(argv: list[str] | None = None) -> None:
    load_env()
    ap = argparse.ArgumentParser(prog="python -m audit", description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    p = sub.add_parser("data"); p.add_argument("--seed", type=int, default=42); p.set_defaults(fn=cmd_data)
    sub.add_parser("up").set_defaults(fn=cmd_up)
    sub.add_parser("down").set_defaults(fn=cmd_down)
    p = sub.add_parser("run")
    p.add_argument("--mode", choices=["live", "scripted"], default="live")
    p.add_argument("--script", default="clean", choices=["clean", "corrupted", "injected", "web_attempt"])
    p.add_argument("--timeout", type=int, default=1800, help="wall-clock limit per attempt (seconds)")
    p.add_argument("--budget", type=float, default=3.0, help="max_budget_usd per attempt")
    p.add_argument("--max-turns", type=int, default=80)
    p.set_defaults(fn=cmd_run)
    sub.add_parser("relay").set_defaults(fn=cmd_relay)
    p = sub.add_parser("execute"); p.add_argument("--redeliver", action="store_true"); p.set_defaults(fn=cmd_execute)
    p = sub.add_parser("review")
    p.add_argument("action", choices=["list", "show", "approve", "reject"])
    p.add_argument("id", type=int, nargs="?")
    p.add_argument("--by", default="auditor")
    p.add_argument("--note")
    p.set_defaults(fn=cmd_review)
    sub.add_parser("verify-log").set_defaults(fn=cmd_verify_log)
    p = sub.add_parser("eval")
    p.add_argument("--n", type=int, default=3); p.add_argument("--k", type=int, default=2)
    p.add_argument("--mode", choices=["live", "scripted"], default="live")
    p.add_argument("--budget", type=float, default=3.0); p.add_argument("--timeout", type=int, default=1800)
    p.set_defaults(fn=cmd_eval)
    p = sub.add_parser("demo"); p.add_argument("--offline", action="store_true"); p.add_argument("--skip-up", action="store_true")
    p.set_defaults(fn=cmd_demo)
    args = ap.parse_args(argv)
    if args.cmd == "review" and args.action != "list" and args.id is None:
        ap.error("review show/approve/reject needs an item id")
    result = args.fn(args)
    if args.cmd == "verify-log" and result is False:
        sys.exit(1)
